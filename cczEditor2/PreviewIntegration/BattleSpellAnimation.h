  const auto stored=battle_spell_detail::be32(bytes,table),decoded=battle_spell_detail::be32(bytes,table+4),offset=battle_spell_detail::be32(bytes,table+8);
  if(!stored||offset>bytes.size()||stored>bytes.size()-offset){result.diagnostic=L"MEff 资源范围无效";return result;}
