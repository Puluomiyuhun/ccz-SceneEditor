#pragma once

#include <ccz/preview/execution_model.h>

#include <cstddef>
#include <cstdint>
#include <string>
#include <vector>

namespace ccz::preview {

enum class PlaybackRange : std::uint8_t {
    StartToTarget,
    TargetToEnd,
};

enum class PlaybackSegmentKind : std::uint8_t {
    Instant,
    Hold,
    CharacterMove,
    PortraitMove,
};

struct PlaybackEvent {
    LogicalNodeKey logical_key;
    RuntimeNodeHandle runtime_handle{};
    DialogueCommandView command;
    PlaybackSegmentKind kind{PlaybackSegmentKind::Instant};
    // Preview duration units are deliberately abstract.  The editor maps
    // movement units to a configured duration after it knows the current
    // coordinate state; core playback never claims they are milliseconds.
    std::int32_t duration_units{};
    // A 0x14 command may contain multiple embedded dialogues.  Non-dialogue
    // events keep the count at zero; dialogue events are numbered from zero.
    std::size_t dialogue_segment_index{};
    std::size_t dialogue_segment_count{};
};

struct PlaybackTimeline {
    std::vector<PlaybackEvent> events;
    // First event generated by the selected logical node.  For a multi-
    // dialogue 0x14 node this is the first embedded dialogue segment.
    std::size_t target_index{};
    // One-past the last event generated by the selected logical node.
    std::size_t target_end_index{};
    // The events vector describes the complete reachable Section path.  The
    // active playback range is a half-open slice so UI progress can remain
    // anchored to the Section origin even for TargetToEnd playback.
    std::size_t range_begin{};
    std::size_t range_end{};
    // For TargetToEnd playback the editor needs the state immediately before
    // the target in order to show a real pre-transition frame.  Empty means
    // the target is the first executable event on the selected path.
    LogicalNodeKey pre_target_key;
    bool complete{};
    std::wstring diagnostic;
};

// Coalesce adjacent movement commands inside the active range. Repeated targets start a new group.
PlaybackTimeline group_consecutive_character_moves(const PlaybackTimeline& timeline);

PlaybackTimeline build_playback_timeline(
    const SectionExecutionModel& model,
    const LogicalNodeKey& target_node,
    PlaybackRange range,
    const ReplayOptions& options);

}  // namespace ccz::preview
