struct ColorTextRun {std::wstring text;int color=-1;};
inline std::vector<ColorTextRun> parse_color_text(const std::wstring& text) {
 std::vector<ColorTextRun> runs;int color=-1,saved=-1;bool active=false;
 auto digit=[](wchar_t c)->int {return c>=L'0'&&c<=L'9'?c-L'0':c>=L'A'&&c<=L'F'?c-L'A'+10:-1;};
 for(std::size_t i=0;i<text.size();) {
  if(i+3<text.size() && text[i]==L'[' && text[i+1]==L'C' && digit(text[i+2])>=0 && digit(text[i+3])>=0) {
   saved=color;active=true;color=digit(text[i+2])*16+digit(text[i+3]);i+=4;continue;
  }
  if(text[i]==L']' && active) {color=saved;active=false;++i;continue;}
  if(runs.empty() || runs.back().color!=color) runs.push_back({L"",color});
  runs.back().text+=text[i++];
 }
 return runs;
}
// Resolve the palette operand of the verified pixel conversion instruction.
// The address belongs to this PE file; it is never treated as process memory.
inline std::vector<std::uint32_t> extract_text_palette(const std::vector<std::uint8_t>& bytes) {
 auto read32=[&](std::size_t at)->std::uint32_t {
  if(at>bytes.size() || bytes.size()-at<4) return 0;
  return bytes[at]|(static_cast<std::uint32_t>(bytes[at+1])<<8)|(static_cast<std::uint32_t>(bytes[at+2])<<16)|(static_cast<std::uint32_t>(bytes[at+3])<<24);
 };
 auto read16=[&](std::size_t at)->std::uint16_t {return at+1<bytes.size()?static_cast<std::uint16_t>(bytes[at]|bytes[at+1]<<8):0;};
 if(bytes.size()<64 || read16(0)!=0x5a4d) return {};
 auto nt=static_cast<std::size_t>(read32(0x3c));
 if(nt>bytes.size() || bytes.size()-nt<56 || read32(nt)!=0x4550 || read16(nt+24)!=0x10b) return {};
 auto count=read16(nt+6),optional=read16(nt+20);auto imageBase=read32(nt+52);
 if(count==0 || count>96 || optional<32) return {};
 auto table=nt+24+optional;if(table>bytes.size() || count*40u>bytes.size()-table) return {};
 std::size_t found=bytes.size();
 for(std::size_t i=0;i+14<=bytes.size();++i) {
  if(bytes[i]!=0x8b || bytes[i+1]!=0x14 || bytes[i+2]!=0x95 || bytes[i+7]!=0x89 || bytes[i+8]!=0x10 || bytes[i+9]!=0x83 || bytes[i+10]!=0xc0 || bytes[i+11]!=3 || bytes[i+12]!=0xeb || bytes[i+13]!=0xe1) continue;
  auto address=read32(i+3);if(address<imageBase)continue;auto rva=address-imageBase;
  for(unsigned section=0;section<count;++section) {
   auto at=table+section*40;auto va=read32(at+12),rawSize=read32(at+16),raw=read32(at+20);
   if(rva<va || rva-va>rawSize || rawSize-(rva-va)<1024)continue;
   auto offset=static_cast<std::size_t>(raw)+(rva-va);if(offset>bytes.size() || bytes.size()-offset<1024)continue;
   if(found!=bytes.size() && found!=offset) return {};
   found=offset;
  }
 }
 if(found==bytes.size()) return {};
 std::vector<std::uint32_t> palette(256);
 for(std::size_t i=0;i<256;++i) palette[i]=read32(found+i*4)&0xffffff;
 return palette;
}
